export const translations: Record<Locale, Record<TranslationKey, string>> = {
  "zh-CN": zhCN,
  "en-US": enUS,
};

export function normalizeLocale(raw: string | null | undefined): Locale {
  const tag = (raw || "").trim().toLowerCase();
  // Only Simplified / Traditional Chinese system locales map to zh-CN; all others default to en-US.
  if (tag === "zh" || tag.startsWith("zh-") || tag.startsWith("zh_")) {
    return "zh-CN";
  }
  return "en-US";
}

export function detectSystemLocale(): Locale {
  if (typeof window === "undefined") {
    return "en-US";
  }
  const primary =
    (Array.isArray(window.navigator.languages) && window.navigator.languages.find((l) => Boolean(l && l.trim()))) ||
    window.navigator.language;
  return normalizeLocale(primary);
}

export function getStoredLocale(): Locale {
  if (typeof window === "undefined") {
    return "en-US";
  }
  try {
    const saved = window.localStorage.getItem(LOCALE_STORAGE_KEY);
    if (saved) return normalizeLocale(saved);
    return detectSystemLocale();
  } catch {
    return detectSystemLocale();
  }
}

export function setStoredLocale(locale: Locale): void {
  if (typeof document !== "undefined") {
    document.documentElement.lang = locale;
  }
  if (typeof window !== "undefined") {
    try {
      window.localStorage.setItem(LOCALE_STORAGE_KEY, locale);
    } catch {
      // Ignore storage failures.
    }
  }
}

export function t(locale: Locale, key: TranslationKey, vars?: Record<string, string | number>): string {
  const dict = translations[locale] || translations["zh-CN"];
  let value = dict[key] ?? translations["zh-CN"][key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      value = value.replace(`{${k}}`, String(v));
    }
  }
  return value;
}
